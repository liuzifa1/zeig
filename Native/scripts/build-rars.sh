#!/usr/bin/env bash
# Builds ZeigRarsFFI.xcframework from Native/rars-ffi (the rars crate behind UniFFI) and
# regenerates the Swift bindings in Packages/ZeigKit/Sources/ZeigRars/ZeigRars.swift.
#
#   Native/scripts/build-rars.sh
#
# Steps (each explained in Native/rars-ffi/README.md):
#   1. cargo builds the crate as a static library for every slice.
#   2. uniffi-bindgen reads the interface out of the compiled library and writes Swift code
#      plus a C header and module map describing the exported functions.
#   3. The static libraries and the header become an .xcframework; the Swift file goes into
#      the ZeigRars target, which links the framework.
#
# Needs rustup with: aarch64-apple-ios aarch64-apple-ios-sim aarch64-apple-darwin
#   rustup target add aarch64-apple-ios aarch64-apple-ios-sim aarch64-apple-darwin

source "$(dirname "$0")/common.sh"

CRATE="$ROOT/Native/rars-ffi"
SWIFT_OUT="$ROOT/Packages/ZeigKit/Sources/ZeigRars"
export CARGO_TARGET_DIR="$BUILD/cargo"
export IPHONEOS_DEPLOYMENT_TARGET="$IOS_MIN"
export MACOSX_DEPLOYMENT_TARGET="$MACOS_MIN"

rust_target_for() {
    case "$1" in
        ios) echo aarch64-apple-ios ;;
        iossim) echo aarch64-apple-ios-sim ;;
        macos) echo aarch64-apple-darwin ;;
    esac
}

for slice in "${SLICES[@]}"; do
    target="$(rust_target_for "$slice")"
    log "$slice: cargo build ($target)"
    cargo build --manifest-path "$CRATE/Cargo.toml" --release --lib --target "$target" --quiet
    mkdir -p "$BUILD/$slice/ZeigRarsFFI/lib"
    cp "$CARGO_TARGET_DIR/$target/release/libzeig_rars.a" "$BUILD/$slice/ZeigRarsFFI/lib/"
    # Drop debug info and local symbols from the copy (70 MB → 15 MB per slice). Safe on a
    # static library; only Cargo's own dylibs mind being stripped (see Cargo.toml).
    strip -S -x "$BUILD/$slice/ZeigRarsFFI/lib/libzeig_rars.a"
done

log "uniffi-bindgen"
generated="$BUILD/rars-bindings"
rm -rf "$generated" && mkdir -p "$generated"
# Library mode: the interface is read from the compiled Mac library's metadata, so the
# bindings always match the code that was built. It runs inside the crate because it finds
# uniffi.toml (the Swift module names) through `cargo metadata`.
(cd "$CRATE" && cargo run --release --quiet --bin uniffi-bindgen -- \
    generate --library "$CARGO_TARGET_DIR/aarch64-apple-darwin/release/libzeig_rars.dylib" \
    --language swift --out-dir "$generated")

headers="$BUILD/ZeigRarsFFI-headers"
rm -rf "$headers" && mkdir -p "$headers"
cp "$generated/ZeigRarsFFI.h" "$headers/"
# UniFFI names the module map after the module; an .xcframework wants module.modulemap.
cp "$generated/ZeigRarsFFI.modulemap" "$headers/module.modulemap"

mkdir -p "$SWIFT_OUT"
{
    echo "// GENERATED by uniffi-bindgen from Native/rars-ffi/src/lib.rs. Don't edit; run"
    echo "// Native/scripts/build-rars.sh after changing the Rust code."
    echo
    cat "$generated/ZeigRars.swift"
} >"$SWIFT_OUT/ZeigRars.swift"
echo "→ $SWIFT_OUT/ZeigRars.swift"

make_xcframework ZeigRarsFFI "$headers" libzeig_rars.a
